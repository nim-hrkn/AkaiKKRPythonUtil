# ---------------------------------------------------------------- data
@dataclass
class Component:
    type: str
    element: str
    z: float
    conc: float
    spin_moment: Optional[float] = None
    orbital_moment: Optional[float] = None
    charge: Optional[float] = None


@dataclass
class Figure:
    name: str
    caption: str
    svg: Optional[str] = None
    png: Optional[bytes] = None


@dataclass
class ReportData:
    title: str = ""
    formula: str = ""
    formula_full: str = ""
    structure_source: Dict[str, Optional[str]] = field(default_factory=dict)   # cif, poscar, preset, comp
    spacegroup: Optional[dict] = None          # number, symbol, symprec, n_sites
    lattice: Dict[str, object] = field(default_factory=dict)                  # brvtyp, a_bohr, a_angstrom, c/a, ...
    natm: Optional[int] = None
    calc: Dict[str, object] = field(default_factory=dict)                     # code, build, magtyp, sdftyp, ewidth, ...
    scf: Dict[str, object] = field(default_factory=dict)                      # converged, n_iter, rms_last, fermi_level, total_energy_Ry, total_moment
    components: List[Component] = field(default_factory=list)
    tc: Optional[float] = None
    cnd: Optional[dict] = None                 # resistivity, conductivity
    gaes: Optional[dict] = None                # status, ewidth, tried, gap, history
    provenance: List[dict] = field(default_factory=list)                      # step, pk, where
    figures: List[Figure] = field(default_factory=list)

    def summary(self):
        """the numbers a caller (MCP) may want without the HTML."""
        return {"formula": self.formula, "spacegroup": self.spacegroup, "total_energy_Ry": self.scf.get("total_energy_Ry"),
                "total_moment": self.scf.get("total_moment"), "fermi_level": self.scf.get("fermi_level"),
                "converged": self.scf.get("converged"), "tc": self.tc, "cnd": self.cnd,
                "gaes": {k: v for k, v in (self.gaes or {}).items() if k != "history"} or None,
                "figures": [f.name for f in self.figures]}

    def to_dict(self):
        d = asdict(self)
        d["figures"] = [{"name": f.name, "caption": f.caption, "svg": f.svg is not None, "png": f.png is not None} for f in self.figures]
        return d


# ---------------------------------------------------------------- structure helpers
def formula_of(structure):
    """(reduced formula, cell formula) of a pymatgen Structure; partially occupied sites are written as
    '(Rh0.5Pt0.5)' so that a CPA type stays recognisable: Fe(Rh0.5Pt0.5)."""
    from collections import Counter
    parts = []
    for site in structure:
        sp = site.species
        if len(sp) == 1 and abs(list(sp.values())[0] - 1.0) < 1e-6:
            parts.append(str(list(sp.keys())[0]))
        else:
            parts.append("(" + "".join("{}{:g}".format(el, occ) for el, occ in sp.items()) + ")")
    counts = Counter(parts)
    reduced = "".join(k + ("{:g}".format(v) if v != 1 else "") for k, v in counts.items())
    return reduced, structure.composition.formula


def symmetry_of(structure, symprec=1e-3):
    """space group of a pymatgen Structure (spglib through SpacegroupAnalyzer); None when it cannot be found."""
    try:
        from pymatgen.symmetry.analyzer import SpacegroupAnalyzer
        sga = SpacegroupAnalyzer(structure, symprec=symprec)
        return {"number": sga.get_space_group_number(), "symbol": sga.get_space_group_symbol(), "symprec": symprec,
                "n_sites": len(structure), "crystal_system": sga.get_crystal_system()}
    except Exception:  # noqa: BLE001
        return None


def components_from_outputs(type_of_site, local_moment=None, orbital_moment=None, type_charge=None):
    """Component list from AkaikkrJob.get_type_of_site and the per-component lists of get_local_moment /
    get_type_charge (their order is the flattened component order)."""
    from pymatgen.core.periodic_table import Element
    comps = []
    k = 0
    for site in type_of_site:
        for c, short in zip(site["component"], site["comp_shortname"]):
            z = float(c["anclr"])
            try:
                el = Element.from_Z(int(round(z))).symbol if z > 0 else "Vc"
            except Exception:  # noqa: BLE001
                el = short
            comps.append(Component(site["type"], el, z, float(c["conc"]),
                                   _pick(local_moment, k), _pick(orbital_moment, k), _pick(type_charge, k)))
            k += 1
    return comps


def _pick(seq, k):
    try:
        return None if seq is None else float(seq[k])
    except (IndexError, TypeError, ValueError):
        return None


# ---------------------------------------------------------------- figures
def _fig(figsize):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    return plt, plt.subplots(figsize=figsize)


def _store(data, name, fig, caption, plt, style=None):
    from .plot import figure_to_svg, figure_to_png
    data.figures.append(Figure(name, caption, figure_to_svg(fig), figure_to_png(fig)))
    plt.close(fig)


def add_dos_figure(data, energy, dos, ewidth_go=None, lang="en", style=None, ylim_log=None):
    """total DOS [nspin, ne] (down spin mirrored)."""
    from .plot import plot_dos, style_axes
    plt, (fig, ax) = _fig((8, 4))
    plot_dos(ax, energy, dos, ewidth_go=ewidth_go, style=style, mirror_down=True, fill=np.asarray(dos).ndim == 1 or len(dos) == 1)
    ax.legend(frameon=False, fontsize=8)
    style_axes(ax, "$E - E_F$ (Ry)", "DOS (states/Ry)", data.title + ": DOS", style=style)
    fig.tight_layout()
    _store(data, "dos", fig, T[lang]["cap_dos"], plt)


def add_pdos_figure(data, energy, pdos, component_names, ewidth_go=None, lang="en", style=None):
    """PDOS [nspin, ncomp, ne, nl] (NaN padded), one panel per component."""
    from .plot import plot_pdos, style_axes
    pdos = np.asarray(pdos, dtype=float)
    ncomp = pdos.shape[1]
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(ncomp, 1, figsize=(8, 3.0 * ncomp), squeeze=False)
    for ic, ax in enumerate(axes[:, 0]):
        plot_pdos(ax, energy, pdos[:, ic, :, :], ewidth_go=ewidth_go, style=style, l_names=L_NAMES, mirror_down=True)
        ax.legend(frameon=False, fontsize=8)
        name = component_names[ic] if ic < len(component_names) else "component {}".format(ic)
        style_axes(ax, "$E - E_F$ (Ry)", "PDOS (states/Ry)", "{}: PDOS {}".format(data.title, name), style=style, title_size=9)
    fig.tight_layout()
    _store(data, "pdos", fig, T[lang]["cap_pdos"], plt)


def add_awk_figures(data, awk_by_spin, kdist, energy, kcrt, klabel, lang="en", style=None):
    """A(w,k) per spin: awk_by_spin = {"up": array[nk, ne], "dn": ...} (from AwkReader.Awk)."""
    from .plot import plot_awk
    for spin, awk in awk_by_spin.items():
        if awk is None:
            continue
        plt, (fig, ax) = _fig((8, 5))
        mesh = plot_awk(ax, kdist, energy, awk, kcrt, klabel, style=style)
        ax.set_ylabel("$E - E_F$ (Ry)")
        ax.set_title("{}: A(ω,k) spin {}".format(data.title, spin), loc="left", fontsize=10)
        cb = fig.colorbar(mesh, ax=ax, pad=0.02)
        cb.set_label("A(ω,k) (1/Ry)")
        fig.tight_layout()
        _store(data, "awk_{}".format(spin), fig, T[lang]["cap_awk"], plt)


def add_jij_figures(data, jij_table, comp_names_by_type, tc=None, lang="en", style=None):
    """J_ij(R): one figure per type pair, one panel per component pair. jij_table: DataFrame with columns
    type1, type2, comp1, comp2, distance, J_ij(meV) (AkaikkrJob.get_jij_as_dataframe). comp_names_by_type:
    {type: [component short names]}."""
    import math
    from .plot import plot_jij, jij_limits, style_axes
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    df = jij_table
    xlim, ylim = jij_limits(df["distance"].astype(float), df["J_ij(meV)"].astype(float))
    for (t1, t2), dft in df.groupby(["type1", "type2"], sort=False):
        pairs = list(dft.groupby(["comp1", "comp2"], sort=False))
        ncols = min(len(pairs), 3)
        nrows = math.ceil(len(pairs) / ncols)
        fig, axes = plt.subplots(nrows, ncols, figsize=(4.2 * ncols, 3.0 * nrows), squeeze=False, sharey=True)
        for ax in axes.flat[len(pairs):]:
            ax.set_visible(False)
        for ax, ((c1, c2), dfc) in zip(axes.flat, pairs):
            n1 = comp_names_by_type.get(t1, [])
            n2 = comp_names_by_type.get(t2, [])
            c1name = n1[int(c1) - 1] if 0 < int(c1) <= len(n1) else "comp{}".format(c1)
            c2name = n2[int(c2) - 1] if 0 < int(c2) <= len(n2) else "comp{}".format(c2)
            plot_jij(ax, dfc["distance"].astype(float), dfc["J_ij(meV)"].astype(float), style=style, xlim=xlim, ylim=ylim)
            style_axes(ax, "$R / a$", "$J_{ij}$ (meV)", "{}-{}".format(c1name, c2name), style=style, title_size=10)
        title = "{}: $J_{{ij}}$ {} - {}".format(data.title, t1, t2) + ("   (Tc = {:.1f} K)".format(tc) if tc is not None else "")
        fig.suptitle(title, x=0.01, ha="left", fontsize=10)
        fig.tight_layout(rect=(0, 0, 1, 0.95))
        _store(data, "jij_{}-{}".format(t1, t2), fig, T[lang]["cap_jij"], plt)


