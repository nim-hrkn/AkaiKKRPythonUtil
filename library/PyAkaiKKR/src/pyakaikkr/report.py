def _fmt(v, nd=4):
    if v is None:
        return "—"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, float):
        return ("{:.%df}" % nd).format(v)
    return html.escape(str(v))


def _row(k, v, num=False):
    return "<tr><th>{}</th><td{}>{}</td></tr>".format(html.escape(k), ' class="num"' if num else "", v)


def render_html(data: ReportData, lang="en", embed="svg", css=None) -> str:
    """one self-contained HTML page. lang: "en" | "ja". embed: "svg" (inline SVG) | "png" (data URI)."""
    if lang not in T:
        raise ValueError("lang must be one of {}".format(LANGS))
    t = T[lang]
    from .plot import data_uri
    out = ['<!DOCTYPE html>', '<html lang="{}"><head><meta charset="utf-8">'.format(lang),
           "<title>{} — {}</title>".format(html.escape(data.title or data.formula), t["title"]),
           "<style>{}</style></head><body>".format(css or _CSS),
           "<h1>{}: {}</h1>".format(t["title"], html.escape(data.title or data.formula))]
    # structure
    out.append("<h2>{}</h2><table>".format(t["structure"]))
    out.append(_row(t["formula"], _fmt(data.formula)))
    out.append(_row(t["formula_full"], _fmt(data.formula_full)))
    src = data.structure_source or {}
    src_txt = ", ".join("{}: {}".format(t.get(k, k), html.escape(str(v))) for k, v in src.items() if v)
    out.append(_row(t["source"], src_txt or t["none"]))
    sg = data.spacegroup
    out.append(_row(t["spacegroup"], "{} ({}), {}, symprec {:g}".format(html.escape(str(sg["symbol"])), sg["number"],
                                                                        html.escape(str(sg.get("crystal_system", ""))), sg.get("symprec", 0))
                    if sg else t["none"]))
    lat = data.lattice or {}
    lat_txt = ", ".join("{} = {}".format(html.escape(str(k)), _fmt(v, 5)) for k, v in lat.items() if v not in (None, "", 0.0) or k in ("brvtyp",))
    out.append(_row(t["lattice"], lat_txt or t["none"]))
    out.append(_row(t["natm"], _fmt(data.natm)))
    out.append("</table>")
    # calculation
    if data.calc:
        out.append("<h2>{}</h2><table>".format(t["calc"]))
        for k, v in data.calc.items():
            out.append(_row(t.get(k, k), _fmt(v, 6)))
        out.append("</table>")
    # scf
    if data.scf:
        out.append("<h2>{}</h2><table>".format(t["scf"]))
        conv = data.scf.get("converged")
        out.append(_row(t["converged"], t["none"] if conv is None else (t["yes"] if conv else t["no"])))
        for k, nd in (("n_iter", 0), ("rms_last", 3), ("fermi_level", 5), ("total_energy_Ry", 6), ("total_moment", 4)):
            if k in data.scf and data.scf[k] is not None:
                label = t["total_energy"] if k == "total_energy_Ry" else t.get(k, k)
                out.append(_row(label, _fmt(data.scf[k], nd), num=True))
        out.append("</table>")
    # components
    if data.components:
        out.append("<h2>{}</h2><table><tr>".format(t["components"]) + "".join(
            "<th>{}</th>".format(t[k]) for k in ("type", "element", "z", "conc", "spin_moment", "orbital_moment", "charge")) + "</tr>")
        for c in data.components:
            out.append("<tr><td>{}</td><td>{}</td><td class=num>{:g}</td><td class=num>{:g}</td><td class=num>{}</td><td class=num>{}</td><td class=num>{}</td></tr>".format(
                html.escape(c.type), html.escape(c.element), c.z, c.conc, _fmt(c.spin_moment, 4), _fmt(c.orbital_moment, 4), _fmt(c.charge, 4)))
        out.append("</table>")
    if data.tc is not None:
        out.append("<p><b>{}</b>: {}</p>".format(t["tc"], _fmt(data.tc, 1)))
    # figures
    if data.figures:
        out.append("<h2>{}</h2>".format(t["figures"]))
        for f in data.figures:
            if embed == "svg" and f.svg:
                body = f.svg
            elif f.png:
                body = '<img alt="{}" src="{}">'.format(html.escape(f.name), data_uri(f.png))
            else:
                body = "<p>{}</p>".format(t["none"])
            out.append('<figure id="{}">{}<figcaption><b>{}</b> — {}</figcaption></figure>'.format(
                html.escape(f.name), body, html.escape(f.name), html.escape(f.caption)))
    # transport
    if data.cnd:
        out.append("<h2>{}</h2><table>".format(t["transport"]))
        for k, v in data.cnd.items():
            out.append(_row(t.get(k, k), _fmt(v, 6) if not isinstance(v, (list, tuple)) else html.escape(json.dumps(v))))
        out.append("</table>")
    # gaes
    if data.gaes:
        g = data.gaes
        out.append("<h2>{}</h2><table>".format(t["gaes"]))
        out.append(_row(t["gaes_status"], _fmt(g.get("status"))))
        out.append(_row(t["gaes_ewidth"], _fmt(g.get("ewidth"))))
        out.append(_row(t["gaes_tried"], html.escape(", ".join("{:.4f}".format(x) for x in g.get("tried", [])))))
        out.append(_row(t["gaes_gap"], html.escape(str(g.get("gap"))) if g.get("gap") else t["none"]))
        out.append("</table>")
    # provenance
    if data.provenance:
        out.append("<h2>{}</h2><table><tr><th>{}</th><th>{}</th><th>{}</th></tr>".format(t["provenance"], t["step"], t["pk"], t["where"]))
        for p in data.provenance:
            out.append("<tr><td>{}</td><td>{}</td><td>{}</td></tr>".format(html.escape(str(p.get("step", ""))), _fmt(p.get("pk")),
                                                                            html.escape(str(p.get("where", "")))))
        out.append("</table>")
    out.append('<p class="meta">{}</p></body></html>'.format(t["generated"]))
    return "\n".join(out)


def write_report(data: ReportData, path, lang="en", embed="svg", figure_dir=None) -> str:
    """write the HTML (and, when figure_dir is given, the PNG / SVG of every figure as files); returns path."""
    with open(path, "w", encoding="utf-8") as f:
        f.write(render_html(data, lang=lang, embed=embed))
    if figure_dir:
        os.makedirs(figure_dir, exist_ok=True)
        for fig in data.figures:
            if fig.png:
                with open(os.path.join(figure_dir, fig.name + ".png"), "wb") as f:
                    f.write(fig.png)
            if fig.svg:
                with open(os.path.join(figure_dir, fig.name + ".svg"), "w") as f:
                    f.write(fig.svg)
    return path


# ---------------------------------------------------------------- file-based collector
DEFAULT_OUTFILES = {"go": "out_go.log", "dos": "out_dos.log", "spc": "out_spc*.log", "j": "out_j*.log", "cnd": "out_cnd.log"}
BOHR_TO_ANG = 0.529177210903


def _first(directory, pattern):
    hits = sorted(glob.glob(os.path.join(directory, pattern)))
    return os.path.basename(hits[0]) if hits else None


def report_from_directory(directory, outfiles=None, structure_files=None, title=None, lang="en", symprec=1e-3,
                          style=None, code=None, build=None) -> ReportData:
    """ReportData from the specx outputs in `directory` (files that do not exist are skipped)."""
    from .AkaiKkr import AkaikkrJob
    from .AwkReader import AwkReader
    files = dict(DEFAULT_OUTFILES)
    files.update(outfiles or {})
    files = {k: (_first(directory, v) if "*" in v else (v if os.path.isfile(os.path.join(directory, v)) else None)) for k, v in files.items()}
    job = AkaikkrJob(directory)
    data = ReportData(title=title or os.path.basename(os.path.abspath(directory)))
    data.structure_source = dict(structure_files or {})
    go = files.get("go")
    if go is None:
        raise FileNotFoundError("no go output ({}) in {}".format(DEFAULT_OUTFILES["go"], directory))
    # structure
    try:
        struc = job.make_pymatgenstructure(go, change_atom_name=False)
        data.formula, data.formula_full = formula_of(struc)
        data.spacegroup = symmetry_of(struc, symprec)
    except Exception:  # noqa: BLE001
        pass
    sp = job.get_struc_param(go)
    a = float(sp.get("a", 0) or 0)
    data.lattice = {"brvtyp": sp.get("brvtyp"), "a_bohr": a, "a_angstrom": a * BOHR_TO_ANG if a else None}
    for k in ("c/a", "b/a", "alpha", "beta", "gamma"):
        if sp.get(k):
            data.lattice[k] = sp[k]
    _coords, names = job.get_atom_coord(go)
    data.natm = len(names)
    # calculation and scf
    data.calc = {"code": code, "build": build, "magtyp": job.get_magtyp(go), "ewidth": job.get_ewidth(go), "edelt": job.get_edelt(go)}
    data.calc = {k: v for k, v in data.calc.items() if v is not None}
    rms = job.get_rms_error(go)
    data.scf = {"converged": job.get_convergence(go), "n_iter": len(rms), "rms_last": rms[-1] if rms else None,
                "fermi_level": job.get_fermi_level(go), "total_energy_Ry": job.get_total_energy(go), "total_moment": job.get_total_moment(go)}
    tos = job.get_type_of_site(go)
    data.components = components_from_outputs(tos, job.get_local_moment(go, mode="spin"), _try(job.get_local_moment, go, mode="orbital"),
                                              job.get_type_charge(go))
    data.provenance.append({"step": "go", "pk": None, "where": os.path.abspath(directory) + "/" + go})
    ewidth_go = job.get_ewidth(go)
    # dos
    if files.get("dos"):
        energy, dos_block = job.get_dos_as_list(files["dos"])
        add_dos_figure(data, energy, dos_block, ewidth_go=ewidth_go, lang=lang, style=style)
        try:
            e2, pdos_block = job.get_pdos_as_list(files["dos"], output_format="spin_separation")
            pdos = _pad_pdos(pdos_block)
            names = [s for site in tos for s in site["comp_shortname"]]
            add_pdos_figure(data, e2, pdos, names, ewidth_go=ewidth_go, lang=lang, style=style)
        except Exception:  # noqa: BLE001
            pass
        data.provenance.append({"step": "dos", "pk": None, "where": files["dos"]})
    # spc
    if files.get("spc"):
        awk = {}
        pot = job.get_potentialfile(go) or "pot.dat"
        for spin in ("up", "dn"):
            f = os.path.join(directory, "{}_{}.spc".format(pot, spin))
            if os.path.isfile(f) and os.path.getsize(f) > 0:
                try:
                    with open(f) as h:
                        awk[spin] = AwkReader(h)
                except Exception:  # noqa: BLE001 - e.g. an empty pot.dat_dn.spc of a non-magnetic run
                    pass
        klabel = None
        kl = os.path.join(directory, "klabel.json")
        if os.path.isfile(kl):
            with open(kl) as h:
                klabel = ["$" + str(list(v.keys())[0]) + "$" for path in json.load(h)["kpath"] for v in path]
        if awk:
            first = next(iter(awk.values()))
            add_awk_figures(data, {s: r.Awk for s, r in awk.items()}, first.kdist, first.energy, first.kcrt, klabel, lang=lang, style=style)
        data.provenance.append({"step": "spc", "pk": None, "where": files["spc"]})
    # jij
    if files.get("j"):
        try:
            df = job.get_jij_as_dataframe(files["j"])
            data.tc = _try(job.get_curie_temperature, files["j"])
            add_jij_figures(data, df, {site["type"]: [_short(site["type"], s) for s in site["comp_shortname"]] for site in tos},
                            tc=data.tc, lang=lang, style=style)
        except Exception:  # noqa: BLE001
            pass
        data.provenance.append({"step": "jij", "pk": None, "where": files["j"]})
    # cnd
    if files.get("cnd"):
        data.cnd = {"resistivity": _try(job.get_resistivity, files["cnd"]), "conductivity": _try(job.get_conductivity, files["cnd"])}
        data.provenance.append({"step": "cnd", "pk": None, "where": files["cnd"]})
    return data


def _short(type_name, comp_short):
    comp = comp_short[len(type_name) + 1:] if comp_short.startswith(type_name + "_") else comp_short
    return comp.split("_")[0] if comp != comp_short else comp


def _try(func, *a, **k):
    try:
        return func(*a, **k)
    except Exception:  # noqa: BLE001
        return None


def _pad_pdos(pdos_block):
    """[spin][comp][energy][l] lists with unequal l -> array [nspin, ncomp, ne, nl_max] padded with NaN."""
    nspin = len(pdos_block)
    ncomp = len(pdos_block[0])
    ne = len(pdos_block[0][0])
    nl = max(len(pdos_block[s][c][0]) for s in range(nspin) for c in range(ncomp))
    out = np.full((nspin, ncomp, ne, nl), np.nan)
    for s in range(nspin):
        for c in range(ncomp):
            arr = np.asarray(pdos_block[s][c], dtype=float)
            out[s, c, :, :arr.shape[1]] = arr
    return out


