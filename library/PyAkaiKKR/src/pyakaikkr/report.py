def main(argv=None):
    p = argparse.ArgumentParser(prog="kkr-report", description="HTML report of an AkaiKKR calculation directory")
    p.add_argument("directory")
    p.add_argument("-o", "--out", default=None, help="output HTML (default <directory>/report.html)")
    p.add_argument("--lang", default="en", choices=LANGS)
    p.add_argument("--embed", default="svg", choices=("svg", "png"))
    p.add_argument("--title", default=None)
    p.add_argument("--cif", default=None, help="CIF file name to record as the structure source")
    p.add_argument("--poscar", default=None, help="POSCAR file name to record as the structure source")
    p.add_argument("--figure-dir", default=None, help="also write every figure as PNG and SVG into this directory")
    p.add_argument("--go", default=None); p.add_argument("--dos", default=None); p.add_argument("--spc", default=None)
    p.add_argument("--j", default=None); p.add_argument("--cnd", default=None)
    args = p.parse_args(argv)
    outfiles = {k: v for k, v in (("go", args.go), ("dos", args.dos), ("spc", args.spc), ("j", args.j), ("cnd", args.cnd)) if v}
    data = report_from_directory(args.directory, outfiles=outfiles, structure_files={"cif": args.cif, "poscar": args.poscar},
                                 title=args.title, lang=args.lang)
    out = args.out or os.path.join(args.directory, "report.html")
    write_report(data, out, lang=args.lang, embed=args.embed, figure_dir=args.figure_dir)
    print(json.dumps({"html": out, "summary": data.summary()}, indent=1, default=str, ensure_ascii=False))
    return 0


